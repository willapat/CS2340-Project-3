"""Django settings for Alert Assist.

All secrets and environment-specific values come from environment variables
(loaded from a local .env file in development). Never hard-code keys here.
Story-specific settings (LLM keys, Chroma path, ...) can be read straight
from the environment with os.getenv in your own module. Add them to
.env.example so teammates know they exist.
"""
import os
from pathlib import Path

from dotenv import load_dotenv

BASE_DIR = Path(__file__).resolve().parent.parent
load_dotenv(BASE_DIR / ".env")


def env_str(name: str, default: str = "") -> str:
    """Like os.getenv, but an empty value (e.g. `KEY=` in .env) counts as unset."""
    value = os.getenv(name, "").strip()
    return value or default


def env_bool(name: str, default: bool = False) -> bool:
    return env_str(name, str(default)).lower() in {"1", "true", "yes", "on"}


def env_list(name: str, default: str = "") -> list[str]:
    return [item.strip() for item in env_str(name, default).split(",") if item.strip()]


